/** 从一个池子里真随机抽一个，优先避开 exclude 里的菜 */
function pickOne(pool, exclude) {
  const ok = pool.filter((n) => !exclude.has(n));
  const from = ok.length ? ok : pool;   // 全被排除了就只能放水，别卡死
  return from[Math.floor(Math.random() * from.length)];
}

/**
 * 抽今天三餐。返回 { breakfast, lunch, dinner }，每项是 { name, west }。
 *
 * 规则：
 *   · 每餐从中式+西式的池子里抽一个（保证中西都能出）
 *   · 三道里至少一道西式 —— 全中式就重抽一道补上，不然模型老往盖饭钻
 *   · 传入 exclude（最近推过的菜）就能避开重复
 */
export function pickThree(exclude = []) {
  const ex = new Set(exclude);

  const draw = (cn, west) => {
    const pool = [...cn, ...west];
    const name = pickOne(pool, ex);
    return { name, west: west.includes(name) };
  };

  const meals = {
    breakfast: draw(BREAKFAST_CN, BREAKFAST_W),
    lunch: draw(LUNCH_CN, LUNCH_W),
    dinner: draw(DINNER_CN, DINNER_W),
  };

  // 三道全中式 -> 随机挑一餐换成西式，保证中西搭配
  if (!meals.breakfast.west && !meals.lunch.west && !meals.dinner.west) {
    const key = ['breakfast', 'lunch', 'dinner'][Math.floor(Math.random() * 3)];
    const westPool = { breakfast: BREAKFAST_W, lunch: LUNCH_W, dinner: DINNER_W }[key];
    meals[key] = { name: pickOne(westPool, ex), west: true };
  }

  return meals;
}

/** 清单规模（自检会报这个数，方便知道库里有多少菜） */
export function foodCount() {
  return BREAKFAST_CN.length + BREAKFAST_W.length
    + LUNCH_CN.length + LUNCH_W.length
    + DINNER_CN.length + DINNER_W.length;
}
